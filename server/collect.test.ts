// 가상 장치의 원본 보관·명시적 적용·배선 변경 후 재확인을 로컬 서버에서 검사한다.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";
import { sceneFile } from "../scene/files.ts";
import type { Preview } from "../collector/capture.ts";
import { collect } from "./collect.ts";
import { openLibrary } from "./library.ts";
import { startServer } from "./http.ts";

const sample = JSON.parse(readFileSync(new URL("../fixtures/collect/twin-adapters.json", import.meta.url), "utf8"));
test("같은 VID/PID의 두 실물을 따로 맞추고 같은 배선·조건에서만 관측을 재사용한다", async t => {
  mkdirSync("work",{recursive:true});
  const dir = mkdtempSync(join("work", "collect-test-"));
  const server = await startServer({port:0,dataDir:dir});
  t.after(async () => {
    await new Promise<void>((resolve,reject) => server.close(e => e ? reject(e) : resolve()));
    rmSync(dir,{recursive:true,force:true});
  });
  const address = server.address();
  assert(address && typeof address === "object");
  const base = "http://127.0.0.1:" + address.port;
  const post = (body:unknown, tag?:string, origin=base) => fetch(base+"/api/collect",{method:"POST",
    headers:{"Content-Type":"application/json",Origin:origin,...(tag && {"If-Match":tag})},body:JSON.stringify(body)});
  const initial = {sceneId:"network",capture:sample};
  assert.equal((await post(initial,undefined,"https://example.invalid")).status,403);
  const invalid = structuredClone(sample);
  invalid.readings[0].unit="W";
  assert.equal((await post({...initial,capture:invalid})).status,422);
  const preview = await (await post(initial)).json() as Preview;
  const targets = [0,1].map(i => preview.rows[i]!.candidates.find((c:{label:string}) => c.label.includes(i===0?"host-a/lan":"host-b/lan"))!);
  assert(targets.every(t => t && !t.applied));
  assert(preview.rows.slice(2).every((r:{candidates:unknown[]})=>r.candidates.length===0));
  const readings=preview.capture.readings;
  assert.deepEqual(readings.slice(3,5).map((r)=>[r.value,r.reason]),[[null,"Add-Type 사용 불가"],[null,"배터리가 없습니다."]]);
  assert.deepEqual(preview.capture.devices[1]!.hardwareIds,preview.capture.devices[3]!.hardwareIds);
  const picks=targets.map((c,row)=>({row,key:c.key}));
  const apply={sceneId:"network",captureId:preview.captureId,picks};
  assert.equal((await post(apply,preview.etag)).status,422);
  const ids=["host-a","host-b","router","lan-a-wire","lan-b-wire"];
  const contexts=ids.map(instanceId=>({instanceId,firmware:null,measurementCondition:"가상 측정"}));
  assert.equal((await post({...apply,contexts},'"old"')).status,412);
  const response=await post({...apply,contexts},preview.etag);
  assert.equal(response.status,200);
  const {id,additions}=await response.json() as {id:string;additions:number};
  assert.equal(additions,2);
  const sceneResponse=await fetch(base+"/api/scenes/"+id);
  const scene=sceneFile.parse(await sceneResponse.json());
  assert.deepEqual(scene.connections.slice(0,2).map(c=>c.observations![0]!.claim.value),[1000,100]);
  assert(scene.connections[0]!.observations![0]!.ports.every(p=>p.firmware===null));
  assert.equal(scene.personal?.length??0,0);
  assert.equal(scene.sources.filter((s:{title:string;locator:string})=>s.title==="수집기" && s.locator.includes("fixture-1")).length,2);
  const changedSpeed = scene.sources.find(s => s.id === scene.connections[1]!.observations![0]!.claim.sources[0])!;
  const comparison = new URLSearchParams(changedSpeed.locator.slice("verification:".length));
  assert.equal(comparison.get("prediction"), "1000 Mbps");
  assert.equal(comparison.get("different"), "1");
  const again=await (await post({...initial,sceneId:id})).json() as Preview;
  assert.deepEqual(again.rows.slice(0,2).map((r:{candidates:{applied:boolean}[]})=>r.candidates.filter(c=>c.applied).length),[1,1]);
  const saved=await (await post({...apply,sceneId:id,picks:again.rows.slice(0,2).map((r:{candidates:{applied:boolean;key:string}[]},row:number)=>({row,key:r.candidates.find(c=>c.applied)!.key}))},again.etag)).json();
  assert.deepEqual(saved,{id,additions:0});
  assert.equal((await fetch(base+"/api/scenes/"+id)).headers.get("ETag"),sceneResponse.headers.get("ETag"));
  [scene.connections[0]!.parts[0]!.exit,scene.connections[0]!.parts[0]!.entry]=[scene.connections[0]!.parts[0]!.entry,scene.connections[0]!.parts[0]!.exit];
  const changed=await fetch(base+"/api/scenes/"+id,{method:"PUT",headers:{Origin:base,"Content-Type":"application/json","If-Match":again.etag},body:JSON.stringify(scene)});
  assert.equal(changed.status,204);
  const rewired=await (await post({...initial,sceneId:id})).json() as Preview;
  assert.deepEqual(rewired.rows.slice(0,2).map((r:{candidates:{applied:boolean}[]})=>r.candidates.some(c=>c.applied)),[false,true]);
  assert.deepEqual(readdirSync(join(dir,"collect")),[preview.captureId+".json"]);
  assert.deepEqual(JSON.parse(readFileSync(join(dir,"collect",preview.captureId+".json"),"utf8")),sample);
});

test("다시 연 라이브러리에서 같은 배선의 새 측정은 관측 하나에 출처를 보태고 내부 노드는 그 실물에만 남는다",t => {
  mkdirSync("work",{recursive:true});
  const dir = mkdtempSync(join("work","collect-facts-"));
  t.after(() => rmSync(dir,{recursive:true,force:true}));
  let library = openLibrary(".",dir);
  const preview = (sceneId:string,capture:unknown) => collect(dir,library,{sceneId,capture}) as Preview;
  const first = preview("t2-alt-mode",sample);
  const rows = [2,5];
  const picks = rows.map(row => ({row,key:first.rows[row]!.candidates.find(c =>
    c.label.includes("monitor/usb-c") && (row !== 5 || c.label.includes("내부 hub")))!.key}));
  const contexts = ["host","monitor","cable"].map(instanceId => ({instanceId,firmware:null,measurementCondition:null}));
  const result = collect(dir,library,{sceneId:"t2-alt-mode",captureId:first.captureId,picks,contexts},first.etag);
  assert(result.id);
  const before = sceneFile.parse(JSON.parse(library.readScene(result.id)!.text));
  assert.deepEqual(before.personal.filter(p => p.field==="attachment").map(p => [p.instanceId,p.ownerId,p.field,p.claim.value]),[["monitor","usb-c","attachment","hub"]]);
  assert.deepEqual(before.connections[0]!.observations?.map(o => [o.field,o.claim.value]),[["usbMode","Gen 1x1"]]);
  library = openLibrary(".",dir);
  const repeat = preview(result.id,sample);
  assert(rows.every(i => repeat.rows[i]!.candidates.filter(c => c.applied).length === 1));
  const next = preview(result.id,{...sample,capturedAt:"2026-01-03T03:04:05Z"});
  const newPicks = rows.map(row => ({row,key:repeat.rows[row]!.candidates.find(c => c.applied)!.key}));
  collect(dir,library,{sceneId:result.id,captureId:next.captureId,picks:newPicks},next.etag);
  const saved = sceneFile.parse(JSON.parse(library.readScene(result.id)!.text));
  assert.equal(saved.personal.length,before.personal.length);
  assert.equal(saved.personal.find(p => p.field === "attachment")!.claim.sources.length,2);
  assert.equal(saved.connections[0]!.observations!.length,1);
  assert.equal(saved.connections[0]!.observations![0]!.claim.sources.length,2);
  const changed = structuredClone(sample);
  changed.readings[2].value = "High Speed";
  const clash = preview(result.id,changed);
  assert.throws(() => collect(dir,library,{sceneId:result.id,captureId:clash.captureId,picks:newPicks},clash.etag),/기존 측정/);
  assert.equal(library.readScene(result.id)!.etag,clash.etag);
  const medium = structuredClone(sample);
  delete medium.readings[0].medium;
  medium.readings.push({device:null,kind:"batteryRate",value:0,unit:"W"});
  const raw = preview("network",medium);
  assert.equal(raw.rows[0]!.candidates.length,0);
  assert.equal(raw.capture.readings.at(-1)!.value,0);
  assert.equal(raw.rows.at(-1)!.candidates.length,0);
});
